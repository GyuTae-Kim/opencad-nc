/**
 * "NC 예제 열기"용 합성 G-code: 코드로 만든 짧은 프로그램(외부 파일·저작물을 쓰지 않는다).
 * 공구 셋(윤곽 엔드밀·원형 포켓 엔드밀·드릴), 단계 내림 윤곽, 나선 포켓, G81 드릴 사이클을 담는다.
 */

export const NC_SAMPLE_NAME = 'opencad-sample.nc';

const f = (v: number): string => {
  const r = Math.round(v * 1000) / 1000;
  return Number.isInteger(r) ? `${r}.` : String(r);
};

/** 둥근 모서리 직사각형 윤곽(시계 방향 G2, 공구 중심 경로) */
function roundedRect(out: string[], x0: number, y0: number, w: number, hgt: number, r: number, z: number, feed: number): void {
  out.push(`G1 Z${f(z)} F${f(feed / 3)}`);
  out.push(`G1 X${f(x0)} Y${f(y0 + hgt - r)} F${f(feed)}`);
  out.push(`G2 X${f(x0 + r)} Y${f(y0 + hgt)} I${f(r)} J0.`);
  out.push(`G1 X${f(x0 + w - r)}`);
  out.push(`G2 X${f(x0 + w)} Y${f(y0 + hgt - r)} I0. J${f(-r)}`);
  out.push(`G1 Y${f(y0 + r)}`);
  out.push(`G2 X${f(x0 + w - r)} Y${f(y0)} I${f(-r)} J0.`);
  out.push(`G1 X${f(x0 + r)}`);
  out.push(`G2 X${f(x0)} Y${f(y0 + r)} I0. J${f(r)}`);
}

/** 합성 예제 프로그램 글 */
export function ncSampleProgram(): string {
  const o: string[] = [];
  o.push('%');
  o.push('O1001 (OPENCAD SYNTHETIC SAMPLE)');
  o.push('(GENERATED BY THE VIEWER - NOT FROM A REAL MACHINE JOB)');
  o.push('(STOCK 140 X 100 X 20, ORIGIN TOP CENTER)');
  o.push('G21 G17 G90 G40 G49 G80');
  o.push('G54');

  // 1) 바깥 윤곽: 10 mm 엔드밀, 2 mm씩 세 번
  o.push('(T1 D=10. FLAT END MILL - OUTSIDE PROFILE)');
  o.push('T1 M6');
  o.push('S8000 M3');
  o.push('G0 X-65. Y-30. Z25.');
  o.push('G43 H1 Z5. M8');
  for (const z of [-2, -4, -6]) {
    o.push(`(PASS Z${f(z)})`);
    roundedRect(o, -65, -45, 130, 90, 12, z, 1200);
    o.push('G1 Y-30.');
    o.push('G0 Z5.');
    o.push('G0 X-65. Y-30.');
  }
  o.push('G0 Z25. M9');

  // 2) 원형 포켓: 6 mm 엔드밀, 나선으로 내려가며 바깥으로 넓힌다
  o.push('(T2 D=6. FLAT END MILL - CIRCULAR POCKET)');
  o.push('T2 M6');
  o.push('S10000 M3');
  o.push('G0 X25. Y0. Z25.');
  o.push('G43 H2 Z3. M8');
  o.push('G1 Z0. F400');
  let z = 0;
  for (let i = 0; i < 4; i++) {
    z -= 1.5;
    o.push(`G3 X25. Y0. I-5. J0. Z${f(z)} F800`);
  }
  for (const r of [8, 11, 14]) {
    o.push(`G1 X${f(20 + r)} Y0. F900`);
    o.push(`G3 X${f(20 + r)} Y0. I${f(-r)} J0.`);
  }
  o.push('G1 X25. Y0.');
  o.push('G0 Z25. M9');

  // 3) 드릴: 8 mm, G81 고정 사이클 격자
  o.push('(T3 D=8. DRILL - HOLE PATTERN)');
  o.push('T3 M6');
  o.push('S3000 M3');
  o.push('G0 X-45. Y-25. Z25.');
  o.push('G43 H3 Z10. M8');
  o.push('G98 G81 X-45. Y-25. Z-15. R2. F250');
  for (const [x, y] of [
    [-45, 0],
    [-45, 25],
    [-25, 25],
    [-25, 0],
    [-25, -25],
  ] as const)
    o.push(`X${f(x)} Y${f(y)}`);
  o.push('G80');
  o.push('G0 Z50. M9');
  o.push('M5');
  o.push('G0 X0. Y60.');
  o.push('M30');
  o.push('%');
  return `${o.join('\n')}\n`;
}
